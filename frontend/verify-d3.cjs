const assert = require('node:assert/strict')
const { page, input, tap } = require('./verify-mobile.cjs')
const { signIn, signOut } = require('./mini-program/data/auth.js')
const demo = require('./mini-program/data/demo.js')

async function main() {
  const originalNow = Date.now
  let now = originalNow()
  Date.now = () => now
  global.wx = { showModal: ({ success }) => success({ confirm: true }), navigateBack() {}, reLaunch() {}, showToast() {} }
  try {
    const id = demo.createBooking('1', 'oil', 'morning', '演示停车位')
    const later = demo.createBooking('2', 'air', 'afternoon', '演示停车位二')
    for (const action of ['accept', 'depart', 'arrive']) assert.equal(demo.applyAction(id, action), true)
    assert.equal(demo.applyAction(id, 'cancel'), false)
    await signIn('demo-tech', 'demo1234')
    const editor = page('quote', { id })
    editor.editReason(input('按目录发布初始保养报价'))
    editor.publish()
    assert.equal(editor.data.error, '')
    const first = demo.getOrder(id)
    const staleOwner = await ownerPage(id)
    await signIn('demo-tech', 'demo1234')
    now += 120000
    const replacement = page('quote', { id })
    replacement.changeQuantity({ currentTarget: { dataset: { id: 'air', delta: 1 } } })
    replacement.editReason(input('补充空调滤芯检查结果'))
    replacement.publish()
    const second = demo.getOrder(id)
    assert.equal(second.quote.total, '318.00')
    assert.equal(second.quote.expiresAt, first.quote.expiresAt)
    assert.equal(second.quotes.find(q => q.id === first.quote.id).status, 'SUPERSEDED')
    await signIn('demo-owner', 'demo1234')
    staleOwner.act(tap('action', 'confirm'))
    assert.match(staleOwner.data.error, /已更新/)
    assert.equal(demo.getOrder(id).status, 'quoted')
    const owner = page('owner', { id })
    owner.act(tap('action', 'confirm'))
    assert.equal(demo.getOrder(id).status, 'ready')
    assert.throws(() => demo.decideQuote(id, 'withdraw', second.quote.id, second.quote.version), /已更新/)
    await signIn('demo-tech', 'demo1234')
    demo.applyAction(id, 'start')
    const approved = demo.getOrder(id)
    const baseline = approved.approvedQuote.items
    function extra(service = 'wiper') {
      const editor = page('quote', { id })
      editor.changeQuantity({ currentTarget: { dataset: { id: service, delta: 1 } } })
      editor.editReason(input('发现新增服务需要车主确认'))
      editor.publish()
      assert.equal(editor.data.error, '')
      return demo.getOrder(id)
    }
    const pending = extra()
    assert.equal(pending.status, 'extraQuoted')
    assert.equal(pending.quote.total, '387.00')
    assert.equal(pending.quote.addedMinutes, 20)
    assert.deepEqual(pending.quote.items.slice(0, baseline.length), baseline)
    assert.equal(pending.approvedQuote.id, approved.approvedQuote.id)
    const techHome = page('orders')
    techHome.selectOwnerOrders(tap('filter', 'quote'))
    assert.ok(techHome.data.ownerOrderRows.some(order => order.id === id))
    const tech = page('technician', { id })
    tech.withdraw()
    assert.equal(tech.data.order.status, 'working')
    assert.equal(tech.data.order.effectiveEnd, approved.committedEnd)
    assert.equal(tech.data.order.quotes[0].status, 'WITHDRAWN')
    assert.deepEqual(tech.data.order.approvedQuote.items, baseline)
    assert.throws(() => demo.decideQuote(id, 'confirm', pending.quote.id, pending.quote.version), /已更新/)
    const rejected = extra()
    const rejectingOwner = await ownerPage(id)
    rejectingOwner.editRejectReason(input('本次暂不更换雨刷'))
    rejectingOwner.reject()
    assert.equal(demo.getOrder(id).status, 'working')
    assert.equal(demo.getOrder(id).quotes[0].reason, rejected.quote.reason)
    assert.equal(demo.getOrder(id).quotes[0].decisionReason, '本次暂不更换雨刷')
    await signIn('demo-tech', 'demo1234')
    const expiring = extra()
    now = expiring.quote.expiresAt
    assert.equal(demo.getOrder(id).status, 'working')
    assert.equal(demo.getOrder(id).quotes[0].status, 'EXPIRED')
    assert.equal(demo.getOrder(id).committedEnd, approved.committedEnd)
    const roundOne = extra()
    demo.decideQuote(id, 'confirm', roundOne.quote.id, roundOne.quote.version)
    const approvedOne = demo.getOrder(id)
    const roundTwo = extra('pressure')
    assert.equal(roundTwo.quote.total, '416.00')
    assert.equal(roundTwo.quote.totalMinutes, 130)
    assert.equal(roundTwo.quote.addedMinutes, 20)
    assert.equal(roundTwo.quote.targetEnd, approvedOne.committedEnd + 20 * 60000)
    assert.deepEqual(roundTwo.quote.items.slice(0, approvedOne.approvedQuote.items.length), approvedOne.approvedQuote.items)
    demo.decideQuote(id, 'confirm', roundTwo.quote.id, roundTwo.quote.version)
    const beforeExtension = demo.getOrder(id)
    const extendPage = page('technician', { id })
    extendPage.editMinutes(input('30'))
    extendPage.editExtensionReason(input('现场操作需要更多时间'))
    extendPage.extend()
    assert.equal(extendPage.data.error, '')
    assert.equal(extendPage.data.order.committedEnd, beforeExtension.committedEnd + 30 * 60000)
    assert.equal(extendPage.data.order.approvedQuote.total, beforeExtension.approvedQuote.total)
    const beforeConflict = demo.getOrder(id)
    assert.throws(() => demo.extendRuntime(id, beforeConflict.rowVersion, demo.getOrder(later).serviceStart + 60000, '与下单时段冲突'), /冲突/)
    const afterConflict = demo.getOrder(id)
    assert.equal(afterConflict.rowVersion, beforeConflict.rowVersion)
    assert.equal(afterConflict.committedEnd, beforeConflict.committedEnd)
    assert.equal(afterConflict.quote.total, beforeConflict.quote.total)
    assert.equal(afterConflict.exceptions.at(-1).type, 'DEFERRAL_SLOT_CONFLICT')
    assert.throws(() => demo.submitQuote(id, {
      rowVersion: afterConflict.rowVersion, pendingQuoteId: null, approvedQuoteId: afterConflict.approvedQuote.id,
      items: [{ lineKey: 'changed', serviceId: 'oil', quantity: 1 }], reason: '篡改已批准范围'
    }), /保留全部/)
    now = afterConflict.committedEnd + 1
    assert.equal(demo.applyAction(id, 'complete'), true)
    assert.equal(demo.getOrder(id).exceptions.at(-1).type, 'OVER_PLAN_COMPLETION')
    assert.equal(demo.getOrder(id).exceptions.at(-1).minutes, 1)
    console.log('D3: replacement deadline, stale decision, catalog pricing, withdrawal, rejection, exact expiry, two EXTRA rounds, immutable scope, extension, conflict rollback and overtime rounding passed')
  } finally {
    Date.now = originalNow
    signOut()
    delete global.wx
  }
}

async function ownerPage(id) {
  await signIn('demo-owner', 'demo1234')
  return page('owner', { id })
}
main().catch(error => { console.error(error); process.exitCode = 1 })
